"""Compiles translations/*.tsv (English<TAB>Chinese<TAB>Urdu, numbers written as #)
into js/locales/zh.js and js/locales/ur.js, and checks every line keeps its placeholders.

usage: python3 scripts/build-locales.py
"""
import glob, json, os, re, sys

ROOT = os.path.join(os.path.dirname(__file__), '..')
rows, problems = {}, []
for path in sorted(glob.glob(os.path.join(ROOT, 'translations', '*.tsv'))):
    for n, line in enumerate(open(path, encoding='utf-8'), 1):
        line = line.rstrip('\n')
        if not line.strip() or line.startswith('//'):
            continue
        parts = line.split('\t')
        if len(parts) != 3:
            problems.append(f'{os.path.basename(path)}:{n}: expected 3 columns, got {len(parts)}'); continue
        en, zh, ur = parts
        want = en.count('#')
        for code, txt in (('zh', zh), ('ur', ur)):
            got = txt.count('#') + len(re.findall(r'\{\d\}', txt))
            if got != want:
                problems.append(f'{os.path.basename(path)}:{n}: {code} has {got} placeholders, English has {want}: {en[:60]}')
        rows[en] = (zh, ur)

os.makedirs(os.path.join(ROOT, 'js', 'locales'), exist_ok=True)
for i, code in enumerate(('zh', 'ur')):
    data = {k: v[i] for k, v in sorted(rows.items())}
    with open(os.path.join(ROOT, 'js', 'locales', f'{code}.js'), 'w', encoding='utf-8') as f:
        f.write('// Generated by scripts/build-locales.py from translations/*.tsv. Edit the TSV files, not this.\n')
        f.write('export default ' + json.dumps(data, ensure_ascii=False, indent=0) + ';\n')
print(f'{len(rows)} strings')
if problems:
    print('\n'.join(problems)); sys.exit(1)
